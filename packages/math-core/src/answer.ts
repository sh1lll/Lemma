import type { Dec } from './decimal';
import type { MathError } from './errors';

/**
 * The shared result schema for every engine other than the core calculator (dates, finance, shopping,
 * currency, timers…). The UI renders any Answer without knowing which engine produced it.
 */
export interface Answer {
  ok: true;
  /** Engine id, e.g. "date", "loan", "tip", "currency". */
  kind: string;
  input: string;
  /** What was understood, stated explicitly: "Monthly payment · $300,000 at 4.5% for 30 years". */
  expression: string;
  primary: { display: string; plain: string; spoken: string; unit?: string };
  /** Becomes the session's previous answer when numeric. */
  value?: Dec;
  /** Labelled detail rows: "Total interest  $247,220.13". */
  lines?: { label: string; display: string }[];
  /** Structured output such as an amortisation schedule or a price comparison. */
  table?: { columns: string[]; rows: string[][]; highlightRow?: number; caption?: string };
  notes: string[];
  /** Provenance for external data (exchange rates): who, and as of when. */
  source?: { name: string; url: string; asOf: string; stale?: boolean };
  /** Typeset mathematics (LaTeX), e.g. the input and the symbolic result. */
  math?: { latex: string; label?: string; collapsed?: boolean }[];
  /** Machine-readable form of a symbolic result in Lemma syntax ("2*x + 3"), for reuse in formulas. */
  symbolic?: string;
  /** Whether the result was independently checked (e.g. differentiating an antiderivative). */
  verified?: { ok: boolean; how: string };
  /** Exact symbolic, numeric approximation, or neither. */
  exactness?: 'exact' | 'approximate' | 'numeric';
  /**
   * Side effect the host performs on commit: timers, reminders, notes… The shapes are defined by the engine
   * that produces them (see productivity-engine's ProductivityAction); hosts narrow on `type`.
   */
  action?: { type: string; [k: string]: unknown };
  /**
   * A chart to draw beside the answer (regression curves, histograms, box plots, a shaded normal curve). Plain
   * data, defined by the engine that produces it (see stats-engine's StatPlot); hosts narrow on `type`.
   */
  plot?: { type: string; [k: string]: unknown };
  /**
   * A small labelled diagram (shapes, triangles, coordinate figures): a self-contained SVG string drawn with
   * currentColor, plus alt text. Generated by the engine from numbers it computed (no user markup inside).
   * `type` is 'svg' when given (the only kind so far).
   */
  figure?: { svg: string; alt?: string; type?: string };
}

export interface AnswerFailure {
  ok: false;
  kind: string;
  input: string;
  error: MathError;
}

export type AnswerResult = Answer | AnswerFailure;
