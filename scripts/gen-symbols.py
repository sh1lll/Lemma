#!/usr/bin/env python3
"""Generates apps/web/src/symbols/unicode.ts: every Unicode math-related character with a readable name.

Run: python3 scripts/gen-symbols.py   (uses Python's own Unicode database; no downloads)
The output is a compact table (runs of consecutive code points, names lowercased) loaded only with the symbol menu.
"""
import os
import unicodedata

BLOCKS = [
    ('Greek', [(0x0391, 0x03A9), (0x03B1, 0x03C9), (0x03D0, 0x03D6), (0x03F0, 0x03F6)]),
    ('Latin-1 and punctuation', [(0x00A2, 0x00A5), (0x00A7, 0x00A7), (0x00AC, 0x00AC), (0x00B0, 0x00B1), (0x00B5, 0x00B7), (0x00D7, 0x00D7), (0x00F7, 0x00F7),
                                 (0x2016, 0x2016), (0x2020, 0x2022), (0x2026, 0x2026), (0x2030, 0x2037), (0x2044, 0x2044), (0x2057, 0x2057)]),
    ('Superscripts and subscripts', [(0x2070, 0x209F)]),
    ('Currency', [(0x20A0, 0x20CF)]),
    ('Combining marks for symbols', [(0x20D0, 0x20F0)]),
    ('Letterlike symbols', [(0x2100, 0x214F)]),
    ('Number forms', [(0x2150, 0x218B)]),
    ('Arrows', [(0x2190, 0x21FF)]),
    ('Mathematical operators', [(0x2200, 0x22FF)]),
    ('Technical', [(0x2300, 0x2312), (0x231C, 0x2321), (0x2329, 0x232A), (0x237C, 0x237C), (0x239B, 0x23B7), (0x23DC, 0x23E1)]),
    ('Geometric shapes', [(0x25A0, 0x25FF)]),
    ('Math symbols A', [(0x27C0, 0x27EF)]),
    ('Supplemental arrows A', [(0x27F0, 0x27FF)]),
    ('Supplemental arrows B', [(0x2900, 0x297F)]),
    ('Math symbols B', [(0x2980, 0x29FF)]),
    ('Supplemental operators', [(0x2A00, 0x2AFF)]),
    ('Math letters', [(0x1D400, 0x1D7FF)]),
]

COMBINING = set(range(0x20D0, 0x20F1))


def nice(cp, name):
    n = name.lower()
    for a, b in (('mathematical ', ''), ('greek small letter ', 'greek '), ('greek capital letter ', 'greek capital '), ('combining ', '')):
        n = n.replace(a, b)
    return n.replace('|', '/')


out = []
total = 0
for title, ranges in BLOCKS:
    runs = []
    for lo, hi in ranges:
        start, names = None, []
        for cp in range(lo, hi + 1):
            try:
                name = unicodedata.name(chr(cp))
            except ValueError:
                name = None
            if name is None:
                if names:
                    runs.append((start, names))
                start, names = None, []
                continue
            if start is None:
                start = cp
            names.append(nice(cp, name))
            total += 1
        if names:
            runs.append((start, names))
    body = '~'.join(f'{s:x}:' + '|'.join(n) for s, n in runs)
    out.append(f'  [{title!r}, {body!r}],')

src = (
    '// Generated by scripts/gen-symbols.py from the Unicode ' + unicodedata.unidata_version + ' database. Do not edit by hand.\n'
    f'// {total} characters: [block title, runs]. A run is "<hex code point>:<name>|<name>|…" for consecutive code points.\n'
    '/* eslint-disable */\n'
    'export const UNICODE_BLOCKS: [string, string][] = [\n' + '\n'.join(out) + '\n];\n'
    f'export const UNICODE_COUNT = {total};\n'
)
dest = os.path.join(os.path.dirname(__file__), '..', 'apps', 'web', 'src', 'symbols', 'unicode.ts')
with open(dest, 'w', encoding='utf-8') as f:
    f.write(src)
print(f'{total} characters → {os.path.relpath(dest)} ({len(src.encode())} bytes)')
